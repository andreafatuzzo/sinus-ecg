def render_full_report(results: ValidationResults) -> str:
    """Render the full validation report as Markdown.

    SRS-009, SRS-012, SRS-014. Sections, in this order: title, the statement that the
    results are not a clinical validation, and the origin of the file; software, data and
    settings; performance targets; results per record; lowest sensitivity; lowest positive
    predictivity; segments not scored; noise stress test (architecture §8.10).

    Args:
        results: The results of the whole evaluation, with the noise stress test.

    Returns:
        The report, ending with one line feed.

    Raises:
        InvalidInputError: If ``results`` covers a subset of the records or has no noise
            stress results.
    """
    if (
        results.subset
        or results.noise_stress is None
        or results.quality is None
        or results.start_of_stream is None
    ):
        raise InvalidInputError(
            "the full report needs the results of the whole evaluation, with the noise stress "
            "test, the signal quality and the start of stream"
        )
    records = _sorted_records(results.records)
    statistics = [record_statistics(record.counts) for record in records]
    aggregate = aggregate_statistics([record.counts for record in records])
    blocks = [
        f"# {_FULL_TITLE}",
        _STATEMENT,
        _FULL_GENERATED_BY,
        *_settings_section(results),
        *_targets_section(aggregate),
        *_records_section(records, statistics, aggregate),
        *_lowest_sections(statistics),
        *_not_scored_section(records),
        *_noise_stress_section(results.noise_stress, results.mitdb),
        *_quality_section(results.quality, results.mitdb.database.title),
        *_start_of_stream_section(results.start_of_stream),
    ]
    return _join(blocks)


def render_subset_report(results: ValidationResults) -> str:
    """Render the subset report as Markdown.

    SRS-009, SRS-012, SRS-016: the items of the full report for the records evaluated,
    without the performance targets and without the noise stress test, and a paragraph that
    states that the report covers a subset of the records for regression checking and is not
    the performance evaluation against the targets (architecture §8.11).
    Sections, in this order: title, the statement that the results are not a clinical
    validation, the subset paragraph and the origin of the file; software, data and
    settings; results per record; lowest sensitivity; lowest positive predictivity;
    segments not scored.

    Args:
        results: The results of a subset of the records.

    Returns:
        The report, ending with one line feed.

    Raises:
        InvalidInputError: If ``results`` does not cover a subset of the records, or holds
            noise stress results.
    """
    if (
        not results.subset
        or results.noise_stress is not None
        or results.quality is not None
        or results.start_of_stream is not None
    ):
        raise InvalidInputError(
            "the subset report needs the results of a subset of the records, without the "
            "noise stress test, the signal quality and the start of stream"
        )
    records = _sorted_records(results.records)
    statistics = [record_statistics(record.counts) for record in records]
    aggregate = aggregate_statistics([record.counts for record in records])
    names = [record.record for record in records]
    noun = "record" if len(names) == 1 else "records"
    paragraph = (
        f"This report covers {noun} {_english_list(names)} of the "
        f"{results.mitdb.database.title}. It is a regression check run on every change, not "
        "the performance evaluation against the targets, which uses all 48 records "
        "(qrs-ec57-report.md)."
    )
    blocks = [
        f"# {_SUBSET_TITLE}",
        _STATEMENT,
        paragraph,
        _SUBSET_GENERATED_BY,
        *_settings_section(results),
        *_records_section(records, statistics, aggregate),
        *_lowest_sections(statistics),
        *_not_scored_section(records),
    ]
    return _join(blocks)


def software_rows(software: SoftwareIdentity) -> tuple[str, str]:
    """Return the two table lines of report section 2 that state the software.

    SRS-009, SRS-012: ``| Software | sinus-dsp <version>, source SHA-256 <digest> |``, with
    the 64 digits of the source digest, and ``| Runtime | Python <python>, <distribution>
    <version>, … |``, with the runtime SOUP packages in the order of ``software.runtime``
    (architecture §8.10, §8.14). Both renderers write these very lines, so that
    :func:`stale_software_rows` compares the text they write.

    Args:
        software: The software identity.

    Returns:
        The line of the row ``Software`` and the line of the row ``Runtime``, without line
        feeds.
    """
    runtime = ", ".join(
        [f"Python {software.python}", *(f"{name} {version}" for name, version in software.runtime)]
    )
    return (
        _row(
            [
                _SOFTWARE_LABEL,
                f"sinus-dsp {software.version}, source SHA-256 {software.source_sha256}",
            ]
        ),
        _row([_RUNTIME_LABEL, runtime]),
    )


def stale_software_rows(text: str, software: SoftwareIdentity) -> tuple[str, ...]:
    """Return how the software rows of a report differ from those of a software identity.

    Each line of ``text`` (split at line feeds; a carriage return at the end of a line is not
    part of it) that starts with ``| Software | `` or ``| Runtime | `` is compared with the
    matching line of :func:`software_rows`. A text that has one of the two rows but not the
    other lacks a row. A text with neither row (e.g. a README) gives no entry (architecture
    §8.14).

    Args:
        text: The text of a report.
        software: The identity the report should state, normally the running software.

    Returns:
        One entry per problem: ``line <n>: <line found>; current: <current line>`` for each
        differing line, in the order of the lines (``n`` from 1), then ``no Software row`` or
        ``no Runtime row``. Empty if the report states this software, or has neither row.
    """
    expected = dict(
        zip(
            (_row_prefix(_SOFTWARE_LABEL), _row_prefix(_RUNTIME_LABEL)),
            software_rows(software),
            strict=True,
        )
    )
    problems: list[str] = []
    found: set[str] = set()
    for number, raw_line in enumerate(text.split("\n"), start=1):
        line = raw_line.removesuffix("\r")
        for prefix, current in expected.items():
            if line.startswith(prefix):
                found.add(prefix)
                if line != current:
                    problems.append(f"line {number}: {line}; current: {current}")
    if found:
        for label in (_SOFTWARE_LABEL, _RUNTIME_LABEL):
            if _row_prefix(label) not in found:
                problems.append(f"no {label} row")
    return tuple(problems)


def _settings_section(results: ValidationResults) -> list[str]:
    """Section 2: software, data and settings."""
    channel = results.settings.channel
    signal = (
        "first stored signal of each record (channel 0)"
        if channel == 0
        else f"channel {channel} of each record"
    )
    matching = (
        "EC57 beat by beat, pairing rules of the WFDB comparator bxb; "
        f"match window {MATCH_WINDOW_MS} ms; "
        f"first {LEARNING_PERIOD_S // 60} min of each record not scored; "
        "ventricular flutter and fibrillation episodes not scored"
    )
    rows = [
        ["Database", _database(results.mitdb)],
        ["Database licence", _licence(results.mitdb)],
        ["Verification", describe_verification(results.mitdb)],
        ["Records", str(len(results.records))],
        ["Signal", signal],
        ["Mains interference filter", f"{results.settings.mains_hz} Hz"],
        ["Matching", matching],
    ]
    lines = [*software_rows(results.software), *(_row(row) for row in rows)]
    return [
        "## Software, data and settings",
        _table_of_lines(["Item", "Value"], [_LEFT, _LEFT], lines),
    ]


def _targets_section(aggregate: AggregateStatistics) -> list[str]:
    """Section 3: the gross Se and +P against the targets."""
    return ["## Performance targets", _targets_table(aggregate)]


def _targets_table(aggregate: AggregateStatistics) -> str:
    """The table of the gross Se and +P against the targets (sections 3 and 9)."""
    target = f"≥ {TARGET_HUNDREDTHS_OF_PERCENT // 100}.{TARGET_HUNDREDTHS_OF_PERCENT % 100:02d}"
    rows = [
        [
            "Gross Se",
            _percent(aggregate.gross_se_percent),
            target,
            _outcome(meets_target(aggregate.tp, aggregate.fn)),
        ],
        [
            "Gross +P",
            _percent(aggregate.gross_ppv_percent),
            target,
            _outcome(meets_target(aggregate.tp, aggregate.fp)),
        ],
    ]
    header = ["Statistic", "Value (%)", "Target (%)", "Result"]
    return _table(header, [_LEFT, _RIGHT, _LEFT, _LEFT], rows)


def _records_section(
    records: Sequence[RecordEvaluation],
    statistics: Sequence[RecordStatistics],
    aggregate: AggregateStatistics,
) -> list[str]:
    """Section 4: the statistics of each record, then the gross and the average values."""
    rows = [
        [
            entry.record,
            record.signal_name,
            str(entry.tp),
            str(entry.fn),
            str(entry.fp),
            _percent(entry.se_percent),
            _percent(entry.ppv_percent),
        ]
        for record, entry in zip(records, statistics, strict=True)
    ]
    rows.append(
        [
            "Gross",
            "",
            str(aggregate.tp),
            str(aggregate.fn),
            str(aggregate.fp),
            _percent(aggregate.gross_se_percent),
            _percent(aggregate.gross_ppv_percent),
        ]
    )
    rows.append(
        [
            "Average",
            "",
            "",
            "",
            "",
            _percent(aggregate.average_se_percent),
            _percent(aggregate.average_ppv_percent),
        ]
    )
    header = ["Record", "Signal", "TP", "FN", "FP", "Se (%)", "+P (%)"]
    align = [_LEFT, _LEFT, _RIGHT, _RIGHT, _RIGHT, _RIGHT, _RIGHT]
    return ["## Results per record", _table(header, align, rows), _averages_sentence(aggregate)]


def _averages_sentence(aggregate: AggregateStatistics) -> str:
    """The paragraph on the averages of section 4 (and of section 9)."""
    n = aggregate.n_records
    return (
        "The averages are the means of the defined per-record values: Se is defined for "
        f"{aggregate.n_se_defined} of {n} records, +P for {aggregate.n_ppv_defined} of "
        f"{n} records."
    )


def _share(n_usable: int, n_windows: int) -> str:
    """A share of windows in percent, from integer counts, or ``not defined``."""
    return _NOT_DEFINED if n_windows == 0 else f"{(100 * n_usable) / n_windows:.2f}"


def _index(value: float | None) -> str:
    """A signal quality index with four decimals, or ``not defined``."""
    return _NOT_DEFINED if value is None else f"{value:.4f}"


def _minutes_seconds(seconds: int) -> str:
    """``m:ss``: minutes without leading zero, two-digit seconds."""
    return f"{seconds // 60}:{seconds % 60:02d}"


def _quality_section(quality: QualityResults, title: str) -> list[str]:
    """Section 8: the signal quality index (SRS-029, SRS-030)."""
    from_start = _minutes_seconds(NOISE_FREE_S)
    stretch_min = NOISY_STRETCH_S // 60
    rows = [
        ["Window length", f"{WINDOW_BLOCKS * BLOCK_MS // 1000} s"],
        ["Window spacing", f"{BLOCK_MS // 1000} s"],
        ["Usable threshold", f"{USABLE_THRESHOLD:.2f}"],
        [
            "Noisy stretches",
            f"from {from_start} to the end of each noise stress record, {stretch_min} min with "
            f"added noise alternating with {stretch_min} min without, starting with noise",
        ],
    ]
    return [
        "## Signal quality index",
        _table(["Item", "Value"], [_LEFT, _LEFT], rows),
        *_quality_noise_blocks(quality, from_start, title),
        *_quality_records_blocks(quality, from_start, title),
        *_quality_criteria_blocks(quality, from_start),
    ]


def _summary_row(label: str, summary: WindowSummary) -> list[str]:
    return [
        label,
        str(summary.n_windows),
        _index(summary.median_index),
        _share(summary.n_usable, summary.n_windows),
    ]


def _quality_noise_blocks(quality: QualityResults, from_start: str, title: str) -> list[str]:
    return [
        "Noise stress records: the windows that lie entirely in a stretch with added noise. "
        f"Records of the {title}: the windows that start at or after "
        f"{from_start}. Noise records: every window.",
        "### Noise stress records",
        _table(
            ["Windows of", "Windows", "Median index", "Usable (%)"],
            [_LEFT, _RIGHT, _RIGHT, _RIGHT],
            [
                *(
                    _summary_row(f"{level} dB", summary)
                    for level, summary in sorted(quality.by_snr, key=lambda entry: -entry[0])
                ),
                _summary_row(
                    f"records {_english_list(CLEAN_RECORDS)}, no added noise, from {from_start}",
                    quality.clean,
                ),
                *(_summary_row(f"noise record {name}", s) for name, s in quality.noise_records),
            ],
        ),
    ]


def _quality_records_blocks(quality: QualityResults, from_start: str, title: str) -> list[str]:
    rows = [
        [
            entry.record,
            str(entry.from_start.n_windows),
            _share(entry.from_start.n_usable, entry.from_start.n_windows),
            str(entry.fn_in_not_usable),
            str(entry.fp_in_not_usable),
        ]
        for entry in quality.records
    ]
    n_windows = sum(entry.from_start.n_windows for entry in quality.records)
    n_usable = sum(entry.from_start.n_usable for entry in quality.records)
    rows.append(
        [
            "Total",
            str(n_windows),
            _share(n_usable, n_windows),
            str(sum(entry.fn_in_not_usable for entry in quality.records)),
            str(sum(entry.fp_in_not_usable for entry in quality.records)),
        ]
    )
    return [
        f"### Records of the {title}",
        _table(
            [
                "Record",
                f"Windows from {from_start}",
                "Usable (%)",
                "FN in not usable windows",
                "FP in not usable windows",
            ],
            [_LEFT, _RIGHT, _RIGHT, _RIGHT, _RIGHT],
            rows,
        ),
        "FN and FP are those of the results per record. Each one that lies in at least one "
        "window marked not usable is counted once. No threshold applies to these figures.",
    ]


def _quality_criteria_blocks(quality: QualityResults, from_start: str) -> list[str]:
    snr = dict(quality.by_snr)
    noise = dict(quality.noise_records)
    passed = dict(quality.criteria)

    def share(summary: WindowSummary | None) -> str:
        return _NOT_DEFINED if summary is None else _share(summary.n_usable, summary.n_windows)

    def median(level: int) -> str:
        summary = snr.get(level)
        return _NOT_DEFINED if summary is None else _index(summary.median_index)

    def percent(value: int) -> str:
        return f"{value:.2f}"

    levels = (24, 18, 12, 6, 0, -6)
    rows: list[tuple[str, str, str]] = [
        (
            "median_non_increasing",
            "Median index from 24 dB to -6 dB",
            ", ".join(median(level) for level in levels),
        ),
        (
            "median_lower_at_lowest_snr",
            "Median index at -6 dB and at 24 dB",
            f"{median(-6)}, {median(24)}",
        ),
        (
            "clean_usable",
            f"Usable windows, records {_english_list(CLEAN_RECORDS)} from {from_start} (%)",
            share(quality.clean),
        ),
    ]
    required = {
        "median_non_increasing": "non-increasing",
        "median_lower_at_lowest_snr": "lower at -6 dB",
        "clean_usable": f"≥ {percent(CLEAN_MIN_USABLE_PERCENT)}",
    }
    for level in HIGH_SNRS_DB:
        name = f"usable_{level}"
        rows.append((name, f"Usable windows at {level} dB (%)", share(snr.get(level))))
        required[name] = f"≥ {percent(HIGH_SNR_MIN_USABLE_PERCENT)}"
    for level in LOW_SNRS_DB:
        name = f"usable_{level}"
        rows.append((name, f"Usable windows at {level} dB (%)", share(snr.get(level))))
        required[name] = f"≤ {percent(LOW_SNR_MAX_USABLE_PERCENT)}"
    for record in NOISE_RECORDS:
        name = f"noise_{record}"
        rows.append((name, f"Usable windows, noise record {record} (%)", share(noise.get(record))))
        required[name] = f"≤ {percent(NOISE_MAX_USABLE_PERCENT)}"
    table_rows = [
        [label, value, required[name], _outcome(passed.get(name, False))]
        for name, label, value in sorted(rows, key=lambda row: QUALITY_CRITERIA.index(row[0]))
    ]
    return [
        "### Criteria",
        _table(
            ["Criterion", "Value", "Required", "Result"],
            [_LEFT, _LEFT, _LEFT, _LEFT],
            table_rows,
        ),
    ]


def _start_of_stream_section(stream: StartOfStreamResults) -> list[str]:
    """Section 9: the start of stream (SRS-023)."""
    starts = ", ".join(_minutes_seconds(start) for start in stream.starts_s)
    rows = [
        ["Segments", f"{stream.segment_s} s each, processed on their own, starting at {starts}"],
        ["Segments per record", str(len(stream.starts_s))],
        ["Start-up period", f"first {LEARNING_S} s of each segment, not scored"],
        ["Detections scored", "marked reliable"],
        [
            "Matching",
            "EC57 beat by beat, pairing rules of the WFDB comparator bxb; "
            f"match window {MATCH_WINDOW_MS} ms; start-up period not scored; "
            "ventricular flutter and fibrillation episodes not scored",
        ],
    ]
    statistics = stream.statistics
    record_rows = [
        [
            entry.record,
            entry.signal_name,
            str(entry.n_segments),
            str(entry.counts.tp),
            str(entry.counts.fn),
            str(entry.counts.fp),
            _percent(record_statistics(entry.counts).se_percent),
            _percent(record_statistics(entry.counts).ppv_percent),
        ]
        for entry in stream.records
    ]
    record_rows.append(
        [
            "Gross",
            "",
            str(sum(entry.n_segments for entry in stream.records)),
            str(statistics.tp),
            str(statistics.fn),
            str(statistics.fp),
            _percent(statistics.gross_se_percent),
            _percent(statistics.gross_ppv_percent),
        ]
    )
    record_rows.append(
        [
            "Average",
            "",
            "",
            "",
            "",
            "",
            _percent(statistics.average_se_percent),
            _percent(statistics.average_ppv_percent),
        ]
    )
    return [
        "## Start of stream",
        _table(["Item", "Value"], [_LEFT, _LEFT], rows),
        "### Results per record",
        _table(
            ["Record", "Signal", "Segments", "TP", "FN", "FP", "Se (%)", "+P (%)"],
            [_LEFT, _LEFT, _RIGHT, _RIGHT, _RIGHT, _RIGHT, _RIGHT, _RIGHT],
            record_rows,
        ),
        _averages_sentence(statistics),
        "### Targets",
        _targets_table(statistics),
    ]


def _lowest_sections(statistics: Sequence[RecordStatistics]) -> list[str]:
    """Section 5: the records with the lowest defined Se, then with the lowest defined +P."""
    blocks: list[str] = []
    for heading, label, values in (
        (
            "Lowest sensitivity",
            "Se",
            [(entry.se_percent, entry.record) for entry in statistics],
        ),
        (
            "Lowest positive predictivity",
            "+P",
            [(entry.ppv_percent, entry.record) for entry in statistics],
        ),
    ):
        defined = sorted((value, record) for value, record in values if value is not None)
        blocks.append(f"## {heading}")
        if not defined:
            blocks.append(f"No record has a defined {label}.")
            continue
        blocks.append(
            f"The records with the lowest defined {label}, at most {_N_LOWEST}, lowest first; "
            "ties are ordered by record name."
        )
        rows = [
            [str(rank), record, _percent(value)]
            for rank, (value, record) in enumerate(defined[:_N_LOWEST], start=1)
        ]
        blocks.append(_table(["Rank", "Record", f"{label} (%)"], [_RIGHT, _LEFT, _RIGHT], rows))
    return blocks


def _not_scored_section(records: Sequence[RecordEvaluation]) -> list[str]:
    """Section 6: the ventricular flutter and fibrillation episodes and what they left out."""
    blocks = ["## Segments not scored", _NOT_SCORED_INTRODUCTION]
    with_episodes = [record for record in records if record.vf_episodes >= 1]
    if with_episodes:
        rows = [
            [
                record.record,
                str(record.vf_episodes),
                str(record.vf_episodes_scored),
                f"{record.vf_samples_scored / record.fs_hz:.1f}",
                str(record.reference_excluded),
                str(record.detections_excluded),
            ]
            for record in with_episodes
        ]
        header = [
            "Record",
            "Episodes in the record",
            "Episodes from 5:00",
            "Duration from 5:00 (s)",
            "Reference beats not scored",
            "Detections not scored",
        ]
        align = [_LEFT, _RIGHT, _RIGHT, _RIGHT, _RIGHT, _RIGHT]
        blocks.append(_table(header, align, rows))
    else:
        blocks.append(_NO_EPISODE)
    flutter_waves = sum(record.flutter_waves_outside_vf for record in records)
    blocks.append(
        "Flutter-wave annotations outside ventricular flutter and fibrillation episodes, "
        f"in all records: {flutter_waves}."
    )
    return blocks


def _noise_stress_section(noise: NoiseStressResults, mitdb: VerificationResult) -> list[str]:
    """Section 7: the noise stress test."""
    database_rows = [
        ["Database", _database(noise.nstdb)],
        ["Database licence", _licence(noise.nstdb)],
        ["Verification", describe_verification(noise.nstdb)],
    ]
    record_rows: list[list[str]] = []
    for record in noise.records:
        entry = record_statistics(record.counts)
        record_rows.append(
            [
                entry.record,
                str(snr_db(entry.record)),
                str(entry.tp),
                str(entry.fn),
                str(entry.fp),
                _percent(entry.se_percent),
                _percent(entry.ppv_percent),
            ]
        )
    snr_rows = [
        _gross_row(str(entry.snr_db), entry.statistics)
        for entry in sorted(noise.by_snr, key=lambda entry: -entry.snr_db)
    ]
    clean_label = f"no added noise ({mitdb.database.title}, records {_english_list(CLEAN_RECORDS)})"
    snr_rows.append(_gross_row(clean_label, noise.clean))
    counts = ["TP", "FN", "FP"]
    return [
        "## Noise stress test",
        _table(["Item", "Value"], [_LEFT, _LEFT], database_rows),
        "### Results per record",
        _table(
            ["Record", "SNR (dB)", *counts, "Se (%)", "+P (%)"],
            [_LEFT, _RIGHT, _RIGHT, _RIGHT, _RIGHT, _RIGHT, _RIGHT],
            record_rows,
        ),
        "### Results per SNR",
        _table(
            ["SNR (dB)", *counts, "Gross Se (%)", "Gross +P (%)"],
            [_LEFT, _RIGHT, _RIGHT, _RIGHT, _RIGHT, _RIGHT],
            snr_rows,
        ),
        _NO_THRESHOLD,
    ]


def _gross_row(label: str, statistics: AggregateStatistics) -> list[str]:
    return [
        label,
        str(statistics.tp),
        str(statistics.fn),
        str(statistics.fp),
        _percent(statistics.gross_se_percent),
        _percent(statistics.gross_ppv_percent),
    ]


def _sorted_records(records: Sequence[RecordEvaluation]) -> list[RecordEvaluation]:
    """The records sorted by name, in code-point order."""
    return sorted(records, key=lambda record: record.record)


def _database(verification: VerificationResult) -> str:
    return f"{verification.database.title}, version {verification.database.version}"


def _licence(verification: VerificationResult) -> str:
    """The value of the row ``Database licence``: ``<name>, <url>`` of the database's licence."""
    licence = verification.database.licence
    return f"{licence.name}, {licence.url}"


def _percent(value: float | None) -> str:
    """A percentage with two decimals, correctly rounded, or ``not defined``."""
    return _NOT_DEFINED if value is None else f"{value:.2f}"


def _outcome(passed: bool) -> str:
    return "pass" if passed else "fail"


def _english_list(items: Sequence[str]) -> str:
    """``a``, ``a and b``, ``a, b and c``."""
    if len(items) <= 1:
        return "".join(items)
    return ", ".join(items[:-1]) + " and " + items[-1]


def _cell(text: str) -> str:
    """A table cell: a vertical bar in the text is escaped."""
    return text.replace("|", "\\|")


def _table(header: Sequence[str], align: Sequence[str], rows: Sequence[Sequence[str]]) -> str:
    """A Markdown table, one line per row."""
    return _table_of_lines(header, align, [_row(row) for row in rows])


def _table_of_lines(header: Sequence[str], align: Sequence[str], lines: Sequence[str]) -> str:
    """A Markdown table whose rows are given as lines already written with :func:`_row`."""
    return "\n".join([_row(header), "|" + "|".join(align) + "|", *lines])


def _row(cells: Sequence[str]) -> str:
    return "| " + " | ".join(_cell(cell) for cell in cells) + " |"


def _row_prefix(label: str) -> str:
    """The start of the line of a table row whose first cell is ``label``: ``| <label> | ``."""
    return f"| {_cell(label)} | "


def _join(blocks: Sequence[str]) -> str:
    """The blocks separated by blank lines, with one line feed at the end."""
    return "\n\n".join(blocks) + "\n"
