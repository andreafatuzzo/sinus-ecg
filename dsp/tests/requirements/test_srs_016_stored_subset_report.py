"""Requirement tests of SRS-016: the subset report stored in the repository (RC-004).

SRS-016 (v0.7.1): the build compares the regenerated subset report with "the subset report
stored in the repository", `docs/validation/qrs-ec57-subset-report.md` (architecture, section
8.11). That stored report shall contain the items of SRS-012 for records 100, 105, 108, 119,
203 and 207, with the outcome of the verification of their files in place of the outcome of
the SRS-001 verification and without the pass or fail of the SRS-007 thresholds, and state
that it covers a subset of records for regression checking and is not the performance
evaluation of SRS-007.

Without data, the tests read the stored file: its statements, its items, the software that it
states (the identity of the package under test, computed by the test as for SRS-012), and the
consistency of its figures (statistics of SRS-011 recomputed from its counts, rankings
recomputed from its values). With the local MIT-BIH Arrhythmia Database (`needs_data`), the
check of the build is run on it and must pass, and the figures that follow from the reference
annotations alone (signals, scored reference beats, ventricular flutter episodes, files
verified) are recomputed by the test from the `.hea`, `.atr` and checksum list files with
wfdb, independently of the software.
"""

from __future__ import annotations

import hashlib
import re
from collections.abc import Callable, Sequence
from fractions import Fraction
from pathlib import Path
from typing import Any

import pytest

from sinus_dsp.evaluation.subset import check_subset_report

pytestmark = pytest.mark.usefixtures("forbid_network")

REPO = Path(__file__).resolve().parents[3]
STORED = REPO / "docs" / "validation" / "qrs-ec57-subset-report.md"
DATA_DIR = REPO / "data"
MITDB_PIN = "b61158a96d5f2ca80edfb354a9a66a6324836c390a84e1966dcee2b907d6be43"
SUBSET = ("100", "105", "108", "119", "203", "207")
STATEMENT = (
    "Technical evaluation only. Sinus is not a medical device; these results are not a "
    "clinical validation."
)
SUBSET_PARAGRAPH = (
    "This report covers records 100, 105, 108, 119, 203 and 207 of the MIT-BIH Arrhythmia "
    "Database. It is a regression check run on every change, not the performance evaluation "
    "against the targets, which uses all 48 records (qrs-ec57-report.md)."
)
ORIGIN = "Generated by dsp/scripts/subset_check.py; do not edit by hand."
SECTIONS = (
    "Software, data and settings",
    "Results per record",
    "Lowest sensitivity",
    "Lowest positive predictivity",
    "Segments not scored",
)
# The beat annotation codes of SRS-002.
BEAT_CODES = frozenset("N L R B A a J S V r F e j n E / f Q ?".split())
FIVE_MINUTES_360 = 108000


@pytest.fixture(scope="module")
def stored_text() -> str:
    """The stored subset report, read as UTF-8."""
    return STORED.read_bytes().decode("utf-8")


def _item(report: Any, label: str) -> str:
    table = report.section("software, data and settings").table_with_row(label)
    assert table.header == ("Item", "Value")
    return str(table.row(label)[1])


def _per_record(report: Any) -> dict[str, tuple[str, ...]]:
    table = report.section("results per record").table_with_row("100")
    assert table.header == ("Record", "Signal", "TP", "FN", "FP", "Se (%)", "+P (%)")
    return {row[0]: row for row in table.rows}


