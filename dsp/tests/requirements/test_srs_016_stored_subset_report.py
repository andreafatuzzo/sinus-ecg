def _episodes(others: Sequence[tuple[int, str]], n_samples: int) -> list[tuple[int, int]]:
    """Ventricular flutter episodes as SRS-008 defines them: from an onset `[` to the next
    offset `]`, both included; without an offset, to the end of the record."""
    episodes: list[tuple[int, int]] = []
    onset: int | None = None
    for sample, symbol in others:
        if symbol == "[" and onset is None:
            onset = sample
        elif symbol == "]" and onset is not None:
            episodes.append((onset, sample))
            onset = None
    if onset is not None:
        episodes.append((onset, n_samples - 1))
    return episodes


def _covered(episodes: Sequence[tuple[int, int]], first: int, last: int) -> set[int]:
    """Samples from ``first`` to ``last`` that lie inside at least one episode."""
    samples: set[int] = set()
    for onset, offset in episodes:
        samples.update(range(max(onset, first), min(offset, last) + 1))
    return samples


@pytest.mark.needs_data
@pytest.mark.requirement("SRS-016")
def test_stored_figures_match_the_reference_annotations(
    stored_text: str, parse_report: Callable[[str], Any]
) -> None:
    """The figures of the stored report that follow from the reference data alone.

    Input: the stored report; for each subset record, its header and reference annotation
    file in `data/mitdb`, read with wfdb by the test; the published checksum list.
    Expected:
    - the checksum list is the pinned one, and it names 28 files of the six records (the
      number that the row "Verification" states);
    - each record is sampled at 360 Hz, and its row gives the name of its first stored
      signal;
    - for each record, TP + FN equals the reference beats (codes of SRS-002) at or after
      5:00 that lie outside every ventricular flutter episode;
    - "Segments not scored" has a row for each record with at least one episode (207 only),
      with the number of episodes in the record, the episodes that reach 5:00 or later,
      their duration from 5:00 with the onset and offset samples (one decimal, in s), and
      the reference beats at or after 5:00 inside them; architecture 8.10 gives 6, 1, 97.9
      and 0 for record 207;
    - the flutter-wave paragraph gives the `!` annotations from 5:00 to the end of the
      records that lie outside every episode (a design figure of the report).
    """
    import wfdb

    folder = DATA_DIR / "mitdb"
    checksum_list = (folder / "SHA256SUMS.txt").read_bytes()
    listed = [line.split(maxsplit=1)[1].lstrip("*") for line in checksum_list.decode().splitlines()]
    subset_files = [
        p for p in listed if "/" not in p and any(p.startswith(f"{r}.") for r in SUBSET)
    ]
    report = parse_report(stored_text)
    rows = _per_record(report)
    not_scored: dict[str, tuple[str, ...]] = {}
    for table in report.section("segments not scored").tables():
        not_scored.update({row[0]: row for row in table.rows})
    expected_not_scored: dict[str, tuple[str, ...]] = {}
    flutter_waves = 0

    assert hashlib.sha256(checksum_list).hexdigest() == MITDB_PIN
    assert len(subset_files) == 28
    for name in SUBSET:
        header = wfdb.rdheader(str(folder / name))
        annotation = wfdb.rdann(str(folder / name), "atr")
        n = int(header.sig_len)
        assert float(header.fs) == 360.0
        assert rows[name][1] == header.sig_name[0], name
        items = list(zip((int(s) for s in annotation.sample), annotation.symbol, strict=True))
        episodes = _episodes([(s, a) for s, a in items if a in ("[", "]")], n)
        inside = _covered(episodes, 0, n - 1)
        scored = [
            s for s, a in items if a in BEAT_CODES and s >= FIVE_MINUTES_360 and s not in inside
        ]
        assert int(rows[name][2]) + int(rows[name][3]) == len(scored), name
        flutter_waves += sum(
            1 for s, a in items if a == "!" and FIVE_MINUTES_360 <= s <= n - 1 and s not in inside
        )
        if episodes:
            from_five = [e for e in episodes if e[1] >= FIVE_MINUTES_360]
            duration = len(_covered(episodes, FIVE_MINUTES_360, n - 1)) / 360.0
            beats_inside = sum(
                1 for s, a in items if a in BEAT_CODES and s >= FIVE_MINUTES_360 and s in inside
            )
            expected_not_scored[name] = (
                str(len(episodes)),
                str(len(from_five)),
                f"{duration:.1f}",
                str(beats_inside),
            )

    assert sorted(not_scored) == sorted(expected_not_scored)
    for name, expected in expected_not_scored.items():
        assert not_scored[name][1:5] == expected, name
    assert expected_not_scored["207"] == ("6", "1", "97.9", "0")
    assert (
        "Flutter-wave annotations outside ventricular flutter and fibrillation episodes, "
        f"in all records: {flutter_waves}."
    ) in report.section("segments not scored").lines
