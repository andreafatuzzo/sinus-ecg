@pytest.mark.requirement("SRS-016")
def test_stored_report_states_the_current_software(stored_text: str, running_software: Any) -> None:
    """The stored report states the software under test, as the regenerated one would.

    Input: `docs/validation/qrs-ec57-subset-report.md`; the identifier of the source code of
    the package under test computed by the test (architecture 8.14), its `__version__`
    literal, and the versions of Python, numpy, scipy and wfdb of the environment that runs
    the test (the environment of `uv.lock`).
    Expected: exactly one line `| Software | sinus-dsp <version>, source SHA-256
    <identifier> |` and one line `| Runtime | Python <major>.<minor>, numpy <v>, scipy <v>,
    wfdb <v> |`, equal to those of the package under test and of this environment (a stored
    report that states another software would make the check of the build fail).
    """
    lines = stored_text.split("\n")

    assert [line for line in lines if line.startswith("| Software |")] == [
        running_software.software_row
    ]
    assert [line for line in lines if line.startswith("| Runtime |")] == [
        running_software.runtime_row
    ]


@pytest.mark.requirement("SRS-016")
def test_stored_report_contains_the_items_of_the_subset_report(
    stored_text: str, parse_report: Callable[[str], Any]
) -> None:
    """The stored report has the statements and items that SRS-016 requires.

    Input: `docs/validation/qrs-ec57-subset-report.md`.
    Expected: the title "# QRS detection: EC57 subset report for regression checking"; the
    statement of SRS-012, the subset paragraph naming the six records and the MIT-BIH
    Arrhythmia Database, and the origin line, before the first section; the sections
    "Software, data and settings", "Results per record", "Lowest sensitivity", "Lowest
    positive predictivity" and "Segments not scored", in this order, and no other (no
    performance targets, no noise stress test, no "pass" or "fail"); the database "MIT-BIH
    Arrhythmia Database, version 1.0.0"; the verification "verified: 28 files match the
    published SHA-256 checksum list (SHA256SUMS.txt, SHA-256 b61158a9…be43); records 100,
    105, 108, 119, 203, 207" (the pinned list of SRS-001); 6 records; channel 0; 60 Hz; one
    row per subset record in the results; UTF-8 text with line feeds, ending with one line
    feed.
    """
    data = STORED.read_bytes()
    report = parse_report(stored_text)
    first_section = min(i for i, level, _ in report.headings if level > 1)
    blocks = "\n".join(report.lines[1:first_section]).split("\n\n")

    assert report.lines[0] == "# QRS detection: EC57 subset report for regression checking"
    assert [b.strip("\n") for b in blocks if b.strip()] == [STATEMENT, SUBSET_PARAGRAPH, ORIGIN]
    assert [title for _, level, title in report.headings if level > 1] == list(SECTIONS)
    assert not re.search(r"\b(pass|fail)\b", stored_text, re.IGNORECASE)
    assert "Target" not in stored_text and "99.50" not in stored_text and "≥" not in stored_text
    assert _item(report, "Database") == "MIT-BIH Arrhythmia Database, version 1.0.0"
    assert _item(report, "Verification") == (
        "verified: 28 files match the published SHA-256 checksum list (SHA256SUMS.txt, "
        f"SHA-256 {MITDB_PIN}); records 100, 105, 108, 119, 203, 207"
    )
    assert _item(report, "Records") == "6"
    assert _item(report, "Signal") == "first stored signal of each record (channel 0)"
    assert _item(report, "Mains interference filter") == "60 Hz"
    assert list(_per_record(report)) == [*SUBSET, "Gross", "Average"]
    assert b"\r" not in data and data.endswith(b"\n") and not data.endswith(b"\n\n")


def _value(text: str) -> Fraction | None:
    return None if text == "not defined" else Fraction(text)


@pytest.mark.requirement("SRS-016")
def test_stored_report_figures_follow_from_its_counts(
    stored_text: str,
    parse_report: Callable[[str], Any],
    percent_text: Callable[[int, int], str],
    mean_percent_text: Callable[[Sequence[tuple[int, int]]], str],
) -> None:
    """The statistics of SRS-011 and the rankings of SRS-012 in the stored report agree with
    its per-record counts.

    Input: `docs/validation/qrs-ec57-subset-report.md`.
    Expected: for each of the six records, Se = TP / (TP + FN) and +P = TP / (TP + FP) in
    percent with two decimals (or "not defined"); the row "Gross" holds the summed counts and
    the gross values; the row "Average" the means of the defined per-record values, and the
    paragraph states how many are defined; each ranking lists, lowest first, at most five
    records with a defined value, ordered by value and then by record name, with the values
    of the table.
    """
    report = parse_report(stored_text)
    rows = _per_record(report)
    counts = {name: tuple(int(rows[name][i]) for i in (2, 3, 4)) for name in SUBSET}

    for name, (tp, fn, fp) in counts.items():
        assert rows[name][5:] == (percent_text(tp, tp + fn), percent_text(tp, tp + fp)), name
    tp, fn, fp = (sum(c[i] for c in counts.values()) for i in range(3))
    assert rows["Gross"] == (
        "Gross",
        "",
        str(tp),
        str(fn),
        str(fp),
        percent_text(tp, tp + fn),
        percent_text(tp, tp + fp),
    )
    se_pairs = [(c[0], c[0] + c[1]) for c in counts.values()]
    ppv_pairs = [(c[0], c[0] + c[2]) for c in counts.values()]
    assert rows["Average"] == (
        "Average",
        "",
        "",
        "",
        "",
        mean_percent_text(se_pairs),
        mean_percent_text(ppv_pairs),
    )
    n_se = sum(1 for _, d in se_pairs if d)
    n_ppv = sum(1 for _, d in ppv_pairs if d)
    assert (
        "The averages are the means of the defined per-record values: Se is defined for "
        f"{n_se} of 6 records, +P for {n_ppv} of 6 records."
    ) in report.section("results per record").lines
    for keyword, column, pairs in (
        ("lowest sensitivity", 5, se_pairs),
        ("lowest positive predictivity", 6, ppv_pairs),
    ):
        defined = sorted(
            (Fraction(100 * n, d), name) for name, (n, d) in zip(SUBSET, pairs, strict=True) if d
        )[:5]
        expected = [
            (str(rank), name, rows[name][column]) for rank, (_, name) in enumerate(defined, start=1)
        ]
        tables = report.section(keyword).tables()
        assert len(tables) == 1
        assert [tuple(row) for row in tables[0].rows] == expected, keyword


