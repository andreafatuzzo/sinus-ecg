@pytest.mark.requirement("SRS-016")
def test_regenerated_report_does_not_depend_on_the_run_or_the_folder(
    tmp_path: Path,
    regenerated: Regenerated,
    subset_fixture: Any,
    copy_subset_fixture: Callable[..., Any],
    make_spike_detector: Callable[[], Any],
) -> None:
    """The report compared with the stored one is the same for every run on the same data.

    Input: the spike subset fixture, regenerated again; and a copy of it in another folder
    whose path holds a space and non-ASCII characters.
    Expected: both reports are byte-identical to the report regenerated earlier.
    """
    again = _regenerate(subset_fixture, _folder(tmp_path / "a"), make_spike_detector)
    copy = copy_subset_fixture(subset_fixture, tmp_path / "copie des données" / "data")
    moved = _regenerate(copy, _folder(tmp_path / "b"), make_spike_detector)

    assert again.data == regenerated.data
    assert moved.data == regenerated.data


def _folder(path: Path) -> Path:
    path.mkdir(parents=True)
    return path


