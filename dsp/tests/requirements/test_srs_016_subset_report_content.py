def _database(
    fixture: Any,
    *,
    title: str = MITDB_TITLE,
    version: str = "1.0.0",
    licence: DatabaseLicence | None = None,
) -> Database:
    """The `Database` of a fixture, pinned to its checksum list, with the fixture licence
    (`FIXTURE_LICENCES` of `conftest.py`) unless another licence is given."""
    return Database(
        slug="mitdb",
        version=version,
        title=title,
        checksum_list_sha256=fixture.checksum_list_sha256,
        licence=fixture.licence if licence is None else licence,
    )


@dataclass(frozen=True)
class Regenerated:
    """A subset report regenerated by the check, and the evaluation it comes from."""

    text: str
    data: bytes
    results: Any
    calls: tuple[tuple[int, float, int], ...]


def _regenerate(
    fixture: Any,
    folder: Path,
    detector_class: Callable[[], Any],
    *,
    database: Database | None = None,
) -> Regenerated:
    """Run the check on ``fixture`` against an absent stored report (one difference), read
    the report it regenerated, and run the evaluation of the check once more."""
    database = database or _database(fixture)
    detector = detector_class()
    with pytest.raises(SubsetReportMismatchError):
        check_subset_report(
            folder / "absent.md",
            fixture.data_root,
            regenerated_path=folder / "regenerated.md",
            database=database,
            detector=detector,
            fetch=None,
        )
    data = (folder / "regenerated.md").read_bytes()
    results = run_subset(
        fixture.data_root, database=database, detector=detector_class(), fetch=None
    )
    return Regenerated(
        text=data.decode("utf-8"), data=data, results=results, calls=tuple(detector.calls)
    )


@pytest.fixture(scope="module")
def regenerated(
    subset_fixture: Any,
    make_spike_detector: Callable[[], Any],
    network_forbidden: Callable[[], Any],
    tmp_path_factory: pytest.TempPathFactory,
) -> Regenerated:
    """The subset report regenerated from the spike subset fixture."""
    folder = tmp_path_factory.mktemp("srs016-content")
    with network_forbidden():
        return _regenerate(subset_fixture, folder, make_spike_detector)


def _lines_starting_with(text: str, prefix: str) -> list[str]:
    return [line for line in text.split("\n") if line.startswith(prefix)]


def _paragraphs(text: str) -> list[str]:
    """The blocks of the report that are neither headings nor tables."""
    blocks = [block for block in text.split("\n\n") if block.strip()]
    return [b.strip("\n") for b in blocks if not b.startswith("#") and not b.startswith("|")]


