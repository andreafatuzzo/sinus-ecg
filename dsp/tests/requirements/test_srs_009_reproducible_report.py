@pytest.mark.requirement("SRS-009")
def test_report_generated_twice_from_fixture_records_is_byte_identical(
    tmp_path: Path,
    evaluation_fixture: Any,
    make_spike_detector: Callable[[], Any],
    reference: Reference,
) -> None:
    """The verification case of SRS-009: two runs on the same inputs.

    Input: the standard fixture databases (14 MIT-BIH and 12 noise stress records), the
    report generated twice into two new folders, each run with its own detector double.
    Expected: the two reports are byte-identical, and identical to the report generated
    earlier in the same process; each output folder holds only the report.
    """
    first_folder, second_folder = tmp_path / "first", tmp_path / "second"
    first_folder.mkdir()
    second_folder.mkdir()

    first = _write_report(evaluation_fixture, first_folder / "report.md", make_spike_detector())
    second = _write_report(evaluation_fixture, second_folder / "report.md", make_spike_detector())

    assert first == second
    assert first == reference.data
    assert [p.name for p in first_folder.iterdir()] == ["report.md"]
    assert [p.name for p in second_folder.iterdir()] == ["report.md"]


@pytest.mark.requirement("SRS-009")
def test_report_written_is_the_rendered_report_in_utf8(
    evaluation_fixture: Any, make_spike_detector: Callable[[], Any], reference: Reference
) -> None:
    """The file written is the report rendered from the evaluation results, in UTF-8.

    Input: the evaluation of the standard fixture, run again, and its full report rendered.
    Expected: the file written for the same inputs holds exactly the UTF-8 encoding of the
    rendered text (no other line ending, no byte-order mark).
    """
    mitdb, nstdb = _databases(evaluation_fixture)
    results = run_validation(
        evaluation_fixture.data_root,
        mitdb=mitdb,
        nstdb=nstdb,
        detector=make_spike_detector(),
        fetch=None,
    )

    assert render_full_report(results).encode("utf-8") == reference.data


@pytest.mark.requirement("SRS-009")
def test_report_depends_on_no_date_time_host_user_or_path(reference: Reference) -> None:
    """The report is plain text that depends only on the data, the software and the settings.

    Input: the report of the standard fixture.
    Expected: valid UTF-8 without a byte-order mark; line feeds only (no carriage return);
    one line feed at the end and no empty line after it; no trailing spaces; neither the
    data folder, nor the output folder, nor the home folder, nor the host name; no date
    (YYYY-MM-DD) and no time of day (hh:mm:ss).
    """
    data = reference.data
    text = data.decode("utf-8")

    assert not data.startswith(codecs.BOM_UTF8)
    assert b"\r" not in data
    assert data.endswith(b"\n") and not data.endswith(b"\n\n")
    assert [line for line in text.split("\n") if line != line.rstrip()] == []
    for folder in (reference.data_root, reference.output.parent, Path.home()):
        assert str(folder) not in text
        assert folder.as_posix() not in text
    host = socket.gethostname()
    if len(host) >= 3:
        assert not re.search(rf"\b{re.escape(host)}\b", text, re.IGNORECASE)
    assert not re.search(r"\b\d{4}-\d{2}-\d{2}\b", text)
    assert not re.search(r"\b\d{1,2}:\d{2}:\d{2}\b", text)


@pytest.mark.requirement("SRS-009")
def test_report_is_identical_from_other_folders_and_processes(
    tmp_path: Path,
    evaluation_fixture: Any,
    copy_evaluation_fixture: Callable[[Any, Path], Any],
    reference: Reference,
) -> None:
    """Two runs of the same inputs on the same software, in other conditions.

    Input: the standard fixture copied to two other data folders (one with a space in its
    path); the report written by two separate Python processes, each started in another
    working folder, with the hash seeds 0 and 4242 and the UTF-8 mode of Python on and off.
    Expected: both reports are byte-identical, and identical to the report written in the
    test process from the original folder.
    """
    driver = tmp_path / "write_report.py"
    driver.write_text(REPORT_DRIVER, encoding="utf-8")
    pins = [evaluation_fixture.mitdb.checksum_list_sha256]
    pins.append(evaluation_fixture.nstdb.checksum_list_sha256)
    runs = [
        ("first", "data", {"PYTHONHASHSEED": "0", "PYTHONUTF8": "1"}),
        ("second run", "data copy", {"PYTHONHASHSEED": "4242", "PYTHONUTF8": "0"}),
    ]
    reports = []
    for folder_name, data_name, env in runs:
        folder = tmp_path / folder_name
        (folder / "work").mkdir(parents=True)
        (folder / "out").mkdir()
        fixture = copy_evaluation_fixture(evaluation_fixture, folder / data_name)
        output = folder / "out" / "qrs-ec57-report.md"
        arguments = [str(driver), str(output), str(fixture.data_root), *pins]

        completed = _python(arguments, cwd=folder / "work", env=env)

        assert completed.returncode == 0, completed.stderr
        reports.append(output.read_bytes())

    assert reports[0] == reports[1]
    assert reports[0] == reference.data


@pytest.mark.requirement("SRS-009")
def test_report_is_identical_when_missing_files_are_downloaded(
    tmp_path: Path,
    evaluation_fixture: Any,
    copy_evaluation_fixture: Callable[[Any, Path], Any],
    make_spike_detector: Callable[[], Any],
    make_fake_fetch: Callable[[dict[str, bytes]], Any],
    reference: Reference,
) -> None:
    """The same report whether the data was already present or obtained by the run.

    Input: a copy of the standard fixture without the MIT-BIH files 101.dat and 118.atr and
    the noise stress file 119e06.hea; a fetch function that serves exactly these three files
    at their PhysioNet addresses (https://physionet.org/files/<database>/1.0.0/<file>).
    Expected: the report is written, byte-identical to the report of the complete local
    copy; each of the three files was asked for and is now present.
    """
    fixture = copy_evaluation_fixture(evaluation_fixture, tmp_path / "data")
    served = {}
    for database, name in ((fixture.mitdb, "101.dat"), (fixture.mitdb, "118.atr")) + (
        (fixture.nstdb, "119e06.hea"),
    ):
        (database.folder.folder / name).unlink()
        url = f"https://physionet.org/files/{database.slug}/1.0.0/{name}"
        served[url] = database.folder.files[name]
    fetch = make_fake_fetch(served)
    output = tmp_path / "out" / "qrs-ec57-report.md"
    output.parent.mkdir()

    data = _write_report(fixture, output, make_spike_detector(), fetch=fetch)

    assert data == reference.data
    assert set(served) <= set(fetch.calls)
    assert (fixture.mitdb.folder.folder / "101.dat").read_bytes() == served[
        "https://physionet.org/files/mitdb/1.0.0/101.dat"
    ]


@pytest.mark.requirement("SRS-009")
def test_report_states_how_it_is_regenerated(
    reference: Reference, parse_report: Callable[[str], Any]
) -> None:
    """The report says which command regenerates it.

    Input: the report of the standard fixture.
    Expected: the line "Generated by dsp/scripts/validate.py; do not edit by hand." before
    the first section of results.
    """
    report = parse_report(reference.data.decode("utf-8"))
    lines = list(report.lines)

    assert GENERATED_BY in lines
    first_section = min(i for i, level, _ in report.headings if level > 1)
    assert lines.index(GENERATED_BY) < first_section


