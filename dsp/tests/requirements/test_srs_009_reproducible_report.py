@pytest.mark.requirement("SRS-009")
def test_single_command_runs_detection_and_writes_the_report_to_docs_validation(
    tmp_path: Path,
    ecg_evaluation_fixture: Any,
    write_command_driver: Callable[[Path], Path],
    parse_report: Callable[[str], Any],
) -> None:
    """The command `validate.py`, with its default output, run twice.

    Input: a copy of the scripts folder of the software in `<repo>/dsp/scripts/`, with an
    existing `<repo>/docs/validation/` folder, as in the repository; the fixture databases of
    6-min noise-free synthetic ECGs (MIT-BIH records 118 at 75 bpm and 119 at 60 bpm, the 12
    noise stress records); the pinned checksum lists set to the fixture lists for these runs
    only. First run: `validate.py --offline --data-dir <fixture>` from `<repo>`; second run:
    the same with `--output <another path>`, from another folder.
    Expected: both runs exit with status 0; the first writes
    `<repo>/docs/validation/qrs-ec57-report.md` and nothing else in that folder; the second
    report is byte-identical to the first. The report comes from the real detector: every
    record has all its reference beats from 5:00 as TP, FN 0, FP 0, Se and +P 100.00, and
    both databases are stated as verified.
    """
    fixture = ecg_evaluation_fixture
    repo = tmp_path / "repo"
    shutil.copytree(
        SCRIPTS_DIR, repo / "dsp" / "scripts", ignore=shutil.ignore_patterns("__pycache__")
    )
    validation = repo / "docs" / "validation"
    validation.mkdir(parents=True)
    script = repo / "dsp" / "scripts" / "validate.py"
    driver = write_command_driver(tmp_path)
    pins = [fixture.mitdb.checksum_list_sha256, fixture.nstdb.checksum_list_sha256]
    options = ["--offline", "--data-dir", str(fixture.data_root)]
    elsewhere = tmp_path / "elsewhere"
    elsewhere.mkdir()
    other_output = elsewhere / "report.md"

    first = _python([str(driver), *pins, str(script), *options], cwd=repo)
    second = _python(
        [str(driver), *pins, str(script), *options, "--output", str(other_output)],
        cwd=elsewhere,
    )

    assert first.returncode == 0, first.stderr
    assert second.returncode == 0, second.stderr
    assert [p.name for p in validation.iterdir()] == ["qrs-ec57-report.md"]
    data = (validation / "qrs-ec57-report.md").read_bytes()
    assert other_output.read_bytes() == data
    report = parse_report(data.decode("utf-8"))
    per_record = report.section("results per record").table_with_row("118")
    for name, record in fixture.mitdb.records.items():
        assert per_record.row(name)[2:] == (str(record.tp), "0", "0", "100.00", "100.00")
    noise = report.section("noise stress").table_with_row("118e24")
    for name, record in fixture.nstdb.records.items():
        assert noise.row(name)[2:] == (str(record.tp), "0", "0", "100.00", "100.00")
    for database in (fixture.mitdb, fixture.nstdb):
        assert f"verified: {database.n_listed_files} files match" in report.text
        assert database.checksum_list_sha256 in report.text
