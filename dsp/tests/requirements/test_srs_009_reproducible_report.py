"""Requirement tests of SRS-009: reproducible validation report (RC-004).

SRS-009: a single command runs QRS detection and the evaluation of SRS-008 and SRS-011 on
the reference database and writes the report of SRS-012 to `docs/validation/`; two runs on
the same inputs and software version produce byte-identical reports.

The reports are generated from the fixture databases of `conftest.py` (records written with
wfdb, RECORDS files, checksum lists, `Database` values pinned to the fixture lists), without
network:
- in the test process, with the detector double of `conftest.py`;
- in separate Python processes, from other folders, with other hash seeds and text
  encodings, to show that nothing in the report depends on the process or the machine;
- through the command itself (`scripts/validate.py`), with the real detector on noise-free
  synthetic ECGs, from a copy of the scripts folder laid out as in the repository. The
  command uses the pinned checksum lists of the software; for these runs only, a driver
  process sets them to the digests of the fixture lists before running the script.
"""

from __future__ import annotations

import codecs
import os
import re
import shutil
import socket
import subprocess
import sys
from collections.abc import Callable, Mapping, Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import pytest

from sinus_dsp.data.physionet import Database
from sinus_dsp.evaluation.report import render_full_report
from sinus_dsp.evaluation.run import run_validation, write_validation_report

pytestmark = pytest.mark.usefixtures("forbid_network")

MITDB_TITLE = "MIT-BIH Arrhythmia Database"
NSTDB_TITLE = "MIT-BIH Noise Stress Test Database"
GENERATED_BY = "Generated by dsp/scripts/validate.py; do not edit by hand."
SCRIPTS_DIR = Path(__file__).resolve().parents[2] / "scripts"

# A script run in separate Python processes: it writes the report of fixture databases with
# a detector double (the samples above 0.5 mV), without network access.
REPORT_DRIVER = '''\
"""Write the validation report of fixture databases with a detector double, without network.

Usage: python <this file> OUTPUT DATA_ROOT MITDB_PIN NSTDB_PIN
"""

import socket
import sys
import urllib.request
from pathlib import Path

import numpy as np


def _refuse(*args, **kwargs):
    raise RuntimeError("network access attempted in a test without network")


socket.socket.connect = _refuse
socket.create_connection = _refuse
socket.getaddrinfo = _refuse
urllib.request.urlopen = _refuse

from sinus_dsp.data.physionet import Database  # noqa: E402
from sinus_dsp.evaluation.run import write_validation_report  # noqa: E402


def spike_detector(signal_mv, fs_hz, mains_hz):
    return np.flatnonzero(np.asarray(signal_mv, dtype=np.float64) > 0.5).astype(np.int64)


output, data_root, mitdb_pin, nstdb_pin = sys.argv[1:5]
write_validation_report(
    Path(output),
    Path(data_root),
    mitdb=Database(
        slug="mitdb",
        version="1.0.0",
        title="MIT-BIH Arrhythmia Database",
        checksum_list_sha256=mitdb_pin,
    ),
    nstdb=Database(
        slug="nstdb",
        version="1.0.0",
        title="MIT-BIH Noise Stress Test Database",
        checksum_list_sha256=nstdb_pin,
    ),
    detector=spike_detector,
    fetch=None,
)
'''


def _databases(fixture: Any) -> tuple[Database, Database]:
    """The two `Database` values of a fixture, pinned to the digests of its checksum lists."""
    mitdb = Database(
        slug="mitdb",
        version="1.0.0",
        title=MITDB_TITLE,
        checksum_list_sha256=fixture.mitdb.checksum_list_sha256,
    )
    nstdb = Database(
        slug="nstdb",
        version="1.0.0",
        title=NSTDB_TITLE,
        checksum_list_sha256=fixture.nstdb.checksum_list_sha256,
    )
    return mitdb, nstdb


def _write_report(
    fixture: Any, output: Path, detector: Any, fetch: Any = None, data_root: Path | None = None
) -> bytes:
    """Write the report of ``fixture`` to ``output`` and return its bytes."""
    mitdb, nstdb = _databases(fixture)
    write_validation_report(
        output,
        data_root if data_root is not None else fixture.data_root,
        mitdb=mitdb,
        nstdb=nstdb,
        detector=detector,
        fetch=fetch,
    )
    return output.read_bytes()


@dataclass(frozen=True)
class Reference:
    """The report of the standard fixture written in the test process, and where."""

    data: bytes
    output: Path
    data_root: Path


@pytest.fixture(scope="module")
def reference(
    evaluation_fixture: Any,
    make_spike_detector: Callable[[], Any],
    network_forbidden: Callable[[], Any],
    tmp_path_factory: pytest.TempPathFactory,
) -> Reference:
    """The report of the standard fixture, written once in the test process."""
    output = tmp_path_factory.mktemp("srs009-reference") / "qrs-ec57-report.md"
    with network_forbidden():
        data = _write_report(evaluation_fixture, output, make_spike_detector())
    return Reference(data=data, output=output, data_root=evaluation_fixture.data_root)


def _python(
    arguments: Sequence[str], cwd: Path, env: Mapping[str, str] | None = None
) -> subprocess.CompletedProcess[str]:
    """Run ``python <arguments>`` in a separate process, with the test environment."""
    return subprocess.run(
        [sys.executable, *arguments],
        cwd=cwd,
        env={**os.environ, **(env or {})},
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        timeout=600,
        check=False,
    )


